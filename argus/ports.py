from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol

from argus.models import PageState


class LifecyclePort(Protocol):
    async def start(self) -> None: ...
    async def stop(self) -> None: ...


class ObservationPort(Protocol):
    @property
    def current_url(self) -> str: ...
    @property
    def has_page(self) -> bool: ...
    async def get_state(self) -> PageState: ...


class VerificationPort(ObservationPort, Protocol):
    async def goto(self, url: str) -> Any: ...
    async def replay(self, start_url: str, actions: list[dict]) -> dict: ...
    async def suspend_mocks(self) -> Any: ...
    async def restore_mocks(self, mocks: Any) -> None: ...


class BrowserPort(LifecyclePort, VerificationPort, Protocol):
    def capture_drops(self) -> dict[str, int]: ...


class ReportPort(Protocol):
    warnings: list[str]

    def generate(self, result: Any, output_dir: str) -> str: ...


class JournalPort(Protocol):
    def read(self, path: Path) -> list[dict]: ...
    def merge(self, path: Path, entries: list[dict]) -> None: ...
